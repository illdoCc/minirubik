/* Reuse the solver's table builders, as the host tests do. */
#define main solver_main
#include "../solver.c"
#undef main

static void print_transitions(const char *label, uint16_t count,
                              uint16_t table[3][count])
{
    /* Ripes uses a byte boundary for .align; halfwords need two bytes. */
    printf("\n.align 2\n%s:\n", label);
    /* Keep the C layout: all R entries, then all B entries, then all D. */
    for (unsigned face = 0; face < 3; ++face) {
        for (uint16_t i = 0; i < count; ++i) {
            if (i % 8 == 0)
                fputs("    .half ", stdout);
            printf("%u", (unsigned) table[face][i]);
            fputs(i % 8 == 7 || i + 1 == count ? "\n" : ", ", stdout);
        }
    }
}

static void print_distances(const char *label, uint16_t count,
                           const uint8_t table[count])
{
    printf("\n%s:\n", label);
    for (uint16_t i = 0; i < count; ++i) {
        if (i % 16 == 0)
            fputs("    .byte ", stdout);
        printf("%u", (unsigned) table[i]);
        fputs(i % 16 == 15 || i + 1 == count ? "\n" : ", ", stdout);
    }
}

int main(void)
{
    search_t search;
    if (!init_search(&search)) {
        fputs("could not build search tables\n", stderr);
        return 1;
    }
    puts("# Generated by tools/gen_tables.c; do not edit by hand.");
    puts("# Transition rows are in R, B, D order; entries are quarter turns.");
    puts("# Four tables occupy 40383 bytes, excluding section alignment.");
    puts(".data");
    print_transitions("permutation_table", PERMUTATIONS, search.permutation);
    print_transitions("orientation_table", ORIENTATIONS, search.orientation);
    print_distances("permutation_distance", PERMUTATIONS,
                    search.permutation_distance);
    print_distances("orientation_distance", ORIENTATIONS,
                    search.orientation_distance);
    return output_failed();
}
